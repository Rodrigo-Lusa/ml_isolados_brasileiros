#!/bin/bash


echo -e "\e[32m____________________________________________________________________________________________________________________________________\e[0m"
echo -e "\e[32mPyTest\e[0m"
# Teste unitários, integração e cobertura de código
docker exec $1 pytest --disable-warnings --cov=./$2/src ./$2/py_test --cov-report html
echo -e "\e[31m____________________________________________________________________________________________________________________________________\e[0m"


echo -e "\e[32m____________________________________________________________________________________________________________________________________\e[0m"
echo -e "\e[32mRuff\e[0m"
# Linting with Ruff
docker exec $1 ruff format ./$2
echo -e "\e[31m____________________________________________________________________________________________________________________________________\e[0m"

echo -e "\e[32m____________________________________________________________________________________________________________________________________\e[0m"
echo -e "\e[32mMyPy\e[0m"
# Type hints
docker exec $1 mypy ./$2 --ignore-missing-imports --follow-imports skip
echo -e "\e[31m____________________________________________________________________________________________________________________________________\e[0m"

echo -e "\e[32m____________________________________________________________________________________________________________________________________\e[0m"
echo -e "\e[32mFlake8\e[0m"
# Style violations, syntax errors, and complexity
docker exec $1 flake8 --max-complexity 12 ./$2
echo -e "\e[31m____________________________________________________________________________________________________________________________________\e[0m"

echo -e "\e[32m____________________________________________________________________________________________________________________________________\e[0m"
echo -e "\e[32mRun Streamlit\e[0m"
# Roda o Streamlit (sem docker restart, para não derrubar os kernels do Jupyter)
docker exec $1 streamlit run ./$2/main.py --server.port=8080 --server.address=0.0.0.0
echo -e "\e[31m____________________________________________________________________________________________________________________________________\e[0m"
